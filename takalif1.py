# ---------------------------
# 3. عملگرهای منطقی (or, and, not)
# ---------------------------
x = True
y = False

print(x or y)
print(x and y)
print(not x)

# ---------------------------
# 4. عملگرهای ریاضی (+ - / * % **)
# ---------------------------
a = 26
b = 6

print(a + b)    # جمع
print(a - b)    # تفریق
print(a / b)    # تقسیم
print(a * b)    # ضرب
print(a % b)    # باقی‌مانده
print(a ** b)   # توان

# ---------------------------
# 5. عملگرهای مقایسه‌ای (== != <= >= < >)
# ---------------------------
print(a == b)
print(a != b)
print(a <= b)
print(a >= b)
print(a < b)
print(a > b)