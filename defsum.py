def sum_n (num1,num2,num3):
    sum=num1+num2+num3
    return sum

def sub_n (num1,num2,num3):
    sub=num1-num2-num3
    return sub

def mult_n (num1,num2,num3):
    mult=num1*num2*num3
    return mult

def div_n (num1,num2,num3):
    div=num1/num2/num3
    return div

s=sum_n(10,2)
su=sub_n(10,5)
m=mult_n(2,6)
d=div_n(10,2)
